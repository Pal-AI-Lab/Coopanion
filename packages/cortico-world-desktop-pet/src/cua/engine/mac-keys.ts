/** The Mac key for a Windows virtual-key code, or null for keys a Mac keyboard lacks (Print Screen, the menu key, F21–F24). */
export function macKey(vk: number): { key: number; flag: number } | null {
  if (MAC_MODIFIERS[vk]) return MAC_MODIFIERS[vk]!;
  const key = KEYS[vk];
  return key === undefined ? null : { key, flag: 0 };
}

/** Quotes a string for AppleScript. */
export const appleString = (s: string): string => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

/** What `display dialog … giving up after` printed: which button, or that time ran out. */
export function dialogAnswer(stdout: string, yes: string): 'yes' | 'no' | 'timeout' {
  if (/gave up:true/.test(stdout)) return 'timeout';
  return new RegExp(`button returned:${yes.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(,|$)`).test(stdout.trim()) ? 'yes' : 'no';
}

/** UTF-16 units of `text` in pieces of at most `size`, never splitting a surrogate pair. */
export function unicodeChunks(text: string, size: number): Uint16Array[] {
  const out: Uint16Array[] = [];
  let cur: number[] = [];
  for (const ch of text) {
    const units = [...Array(ch.length)].map((_, i) => ch.charCodeAt(i));
    if (cur.length + units.length > size) { out.push(Uint16Array.from(cur)); cur = []; }
    cur.push(...units);
  }
  if (cur.length) out.push(Uint16Array.from(cur));
  return out;
}
